import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dist=path.join(root,'dist');
const read=name=>readFile(path.join(dist,name),'utf8');
function wrap(name,code,exports,bindings=''){
  return `const ${name}=(()=>{\n${bindings}\n${code}\nreturn {${exports.join(',')}};\n})();\n`;
}
function removeExports(code){return code.replace(/^export\s+(?=(?:function|const|let|class)\b)/gm,'');}
let vendor=await read('vendor/three-r184.js');
const match=vendor.match(/export\{([^}]+)\};\s*$/);
if(!match)throw new Error('Unsupported Three.js bundle export shape.');
const mappings=match[1].split(',').map(item=>{const pair=item.trim().match(/^([\w$]+)\s+as\s+([\w$]+)$/);if(!pair)throw new Error('Invalid library export.');return `${JSON.stringify(pair[2])}:${pair[1]}`;});
vendor=vendor.slice(0,match.index);
let script=wrap('__vendor',vendor,mappings);
const facade=await read('vendor/three.js');
const facadeMatch=facade.match(/export\s*\{([\s\S]+?)\}\s*from/);
const facadeExports=facadeMatch[1].split(',').map(item=>{const pair=item.trim().match(/^([\w$]+)\s+as\s+([\w$]+)$/);if(!pair)throw new Error('Invalid named export.');return `${pair[2]}:__vendor[${JSON.stringify(pair[1])}]`;});
script+=`const __three={${facadeExports.join(',')}};\n`;
script+=wrap('__content',removeExports(await read('content.js')),['STORAGE_KEY','safeUrl','normalizeContent']);
let world=await read('world.js');world=world.replace(/^import \* as T from .*;\r?\n/m,'').replace(/^export \{ T \};\r?\n/m,'');
script+=wrap('__world',removeExports(world),['T','makeCar','createWorld'],'const T=__three;');
let visual=await read('visual.js');visual=visual.replace(/^import .*;\r?\n/m,'');
script+=wrap('__visual',removeExports(visual),['createScenery'],'const {createWorld,makeCar}=__world;');
script+=wrap('__model',removeExports(await read('game-model.js')),['RULES','collision','createState','boost','tick','awardPass']);
let game=await read('game.js');game=game.replace(/^import .*;\r?\n/gm,'');
script+=wrap('__game',removeExports(game),['createGame'],'const {createWorld,makeCar}=__world;\nconst {RULES,collision,createState,boost,tick,awardPass}=__model;');
const embedded=JSON.stringify(JSON.parse(await read('content.json'))).replace(/</g,'\\u003c');
script+=`const __embeddedContent=${embedded};\n`;
let app=await read('app.js');app=app.replace(/^import .*;\r?\n/m,'');
const fetchLine=/    const \[file,capabilities\]=await Promise\.all\([^\r\n]+\);/;
if(!fetchLine.test(app))throw new Error('Content initialization changed; update the standalone builder.');
app=app.replace(fetchLine,'    const [file,capabilities]=[structuredClone(__embeddedContent),null];');
app=app.replaceAll("import('./game.js')",'Promise.resolve(__game)').replaceAll("import('./visual.js')",'Promise.resolve(__visual)');
script+=wrap('__app',app,[],"const {normalizeContent,safeUrl}=__content; const STORAGE_KEY='nightshift.offline.content.v1';");
new vm.Script(script,{filename:'nightshift-standalone.js'});
let html=await read('index.html');
const css=await read('style.css');
const favicon=await read('assets/favicon.svg');
html=html.replace('<link rel="stylesheet" href="./style.css">',`<style>${css}</style>`);
html=html.replace('href="./assets/favicon.svg"',`href="data:image/svg+xml,${encodeURIComponent(favicon)}"`);
html=html.replace('<script type="module" src="./app.js"></script>',()=>`<script type="module">\n${script.replace(/<\/script/gi,'<\\/script')}\n</script>`);
html=html.replace('资料保存在当前浏览器。可导出备份，用于之后更新网站。','离线单文件版：资料保存在当前浏览器。请导出 JSON 备份，用于之后更新正式网站。');
const destination=process.argv[2]?path.resolve(process.argv[2]):path.join(root,'双击打开主页.html');
await writeFile(destination,html,'utf8');
console.log(`Standalone page created: ${destination}`);
console.log('CSS, content and all scripts are embedded. No local server or external downloads are needed.');
